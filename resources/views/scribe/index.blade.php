        <h1 id="introduction">Introduction</h1>
<p>Market prices of basic goods in the Philippines, compared against DTI suggested retail prices (SRP).</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8000</code>
</aside>
<pre><code>All endpoints live under `/api/v1` and return JSON.

Successful responses wrap the payload in `data`. List endpoints also return `meta` with `page`, `per_page` and `total`, and accept `?page=` and `?per_page=` (max 100).

Errors look like this:

```json
{"error": {"code": "validation_failed", "message": "The given data was invalid.", "details": {"price": ["The price field is required."]}}}
```

Timestamps are ISO 8601 in UTC. Dates (`from`, `to`, `effective_date`) use `YYYY-MM-DD`.</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Get a token from <code>POST /api/v1/auth/register</code> or <code>POST /api/v1/auth/login</code>. Creating or changing commodities, markets and SRPs requires an admin account.</p>

        <h1 id="auth">Auth</h1>

    <p>Accounts and tokens. Tokens are sent as <code>Authorization: Bearer &lt;token&gt;</code> and expire after 30 days. New accounts get a verification email and must verify before submitting price reports.</p>

